def source_colour(x,y):
    x=max(0,min(W-1.001,x));y=max(0,min(H-1.001,y));ix,iy=int(x),int(y);tx,ty=x-ix,y-iy
    a=source.getpixel((ix,iy));b=source.getpixel((ix+1,iy));c=source.getpixel((ix,iy+1));d=source.getpixel((ix+1,iy+1))
    return tuple(round((a[k]*(1-tx)+b[k]*tx)*(1-ty)+(c[k]*(1-tx)+d[k]*tx)*ty) for k in range(3))

def bamboo(slug,fans,stem,widths,nodes,branches,crop,foreground,clean_ranges):
    parts=[{'name':f'{slug} {name} leaf {i+1:02}','polygon':p} for name,polygons in fans for i,p in enumerate(polygons)]
    curves=[{'name':slug+' continuous curved cane','points':sample(stem,widths,96),'stem':True}]
    for name,points,half in branches:
        curves.append({'name':name,'points':sample(points,half),'stem':False,'parent_curve':0})
    parents=curves[:]
    for part in parts:
        x,y=part['polygon'][0]
        parent,point=min(((i,q) for i,c in enumerate(parents) for q in c['points']),key=lambda item:(item[1][0]-x)**2+(item[1][1]-y)**2)
        if math.hypot(point[0]-x,point[1]-y)>.6:
            curves.append({'name':part['name']+' connected petiole','points':sample([point[:2],[x,y]],[.4,.25],12),'stem':False,'parent_curve':parent,'leaf_root':True})
    mask=Image.new('L',(crop[2]-crop[0],crop[3]-crop[1]),0);draw=ImageDraw.Draw(mask)
    for part in parts:draw.polygon([(x-crop[0],y-crop[1]) for x,y in part['polygon']],fill=255)
    for curve in curves:
        for x,y,half in curve['points']:draw.ellipse((x-crop[0]-half,y-crop[1]-half,x-crop[0]+half,y-crop[1]+half),fill=255)
    # The mesh already defines the outline. One source-pixel alpha padding
    # keeps bilinear filtering above the existing .90 cutoff on fine connected
    # petioles; it does not enlarge the geometry or change the site's material.
    texture=source.crop(crop).convert('RGBA');texture.putalpha(mask.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(.2)))
    atlas=Image.new('RGBA',(texture.width+32,texture.height),(0,0,0,0));atlas.paste(texture,(0,0))
    centers=curves[0]['points']
    def cane_at(y):
        for a,b in zip(centers,centers[1:]):
            if a[1]<=y<=b[1]:
                t=(y-a[1])/max(1e-9,b[1]-a[1]);dx,dy=b[0]-a[0],b[1]-a[1];length=max(1e-9,math.hypot(dx,dy))
                return a[0]*(1-t)+b[0]*t,a[2]*(1-t)+b[2]*t,-dy/length,dx/length
        p=min(centers,key=lambda p:abs(p[1]-y));return p[0],p[2],-1,0
    for row in range(texture.height):
        y=row+crop[1];sy=float(y)
        # Sample a neighbouring clean internode only where another approved
        # foreground plant covers the cane in the source photograph.
        for lo,hi,replacement in clean_ranges:
            if lo<=y<=hi:sy=replacement+(y-lo)%12
        x,half,nx,ny=cane_at(sy);collar=max(math.exp(-((sy-node)/1.2)**2) for node in nodes)
        for column in range(32):
            u=(column/31*2-1)*.92
            atlas.putpixel((texture.width+column,row),(*source_colour(x+nx*half*u*(1+.30*collar),sy+ny*half*u),255))
    atlas.save(ASSETS/(slug+'-approved.png'))
    spec={'source_size':[W,H],'approved_front':'bamboo-shoots-reference-20261007/01-approved-front.png','crop':crop,'parts':parts,'curves':curves,'node_y':nodes,
          'world_width':14.222222,'world_height':8,'world_offset':[0,0],'cane_atlas':{'left':texture.width,'width':32,'texture_width':atlas.width},
          'wall_anchor':-.006,'shell_thickness':.003,'root_clearance':{'start_y':1000,'end_y':H,'x_pixels':0,'depth_factor':.65},
          'occlusion_clearance':{'mesh':foreground,'min_y':crop[1],'max_y':H,'gap':.003},'node_profile':{'lip_width':.30,'lip_height':.012,'groove_height':.003},
          'stage':'Remaining approved plants / unified review after completion'}
    (DESIGN/(slug+'-contours.json')).write_text(json.dumps(spec,indent=2),encoding='utf-8')
    print(slug,len(parts),'independent leaves',len(curves),'connected curves')

